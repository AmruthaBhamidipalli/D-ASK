// ─────────────────────────────────────────────────────────────────────────────
// Research exports (2026-11-15): BibTeX bibliographies and LaTeX documents (the report itself, or a research-proposal skeleton built from
// the report's evidence). Everything is generated locally from the saved report, its evidence file and the scholarly library; nothing is
// invented: sections the evidence does not cover are marked for the author to write, and every \cite key exists in references.bib.
// ─────────────────────────────────────────────────────────────────────────────

import type { Paper } from "./scholar";
import { bibKey } from "./scholar";

export interface BibSource { label: string; title: string; path: string }

const LATEX_SPECIAL: Record<string, string> = { "\\": "\\textbackslash{}", "{": "\\{", "}": "\\}", "$": "\\$", "&": "\\&", "#": "\\#", "^": "\\textasciicircum{}", "_": "\\_", "~": "\\textasciitilde{}", "%": "\\%" };
export const latexEscape = (s: string) => s.replace(/[\\{}$&#^_~%]/g, (c) => LATEX_SPECIAL[c]!).replace(/[“”]/g, '"').replace(/[‘’]/g, "'");
const bibEscape = (s: string) => s.replace(/[{}]/g, "").replace(/[&%$#_]/g, (c) => `\\${c}`);

export function bibtexForPaper(p: Paper): string {
  const fields: [string, string | null][] = [
    ["title", `{${bibEscape(p.title)}}`], ["author", p.authors.length ? bibEscape(p.authors.join(" and ")) : null], ["year", p.year ? String(p.year) : null],
    [p.source === "arxiv" ? "howpublished" : "journal", p.venue ? bibEscape(p.venue) : null], ["doi", p.doi], ["url", p.url],
    ["note", p.source === "arxiv" ? "arXiv preprint" : null],
  ];
  const type = p.source === "arxiv" ? "misc" : "article";
  return `@${type}{${p.key},\n${fields.filter(([, v]) => v).map(([k, v]) => `  ${k} = {${v}}`).join(",\n")}\n}`;
}

/** A local document (a path, or a web page the user named): @misc with where it is. */
export function bibtexForLocal(s: BibSource, key: string): string {
  const year = /\b(19|20)\d{2}\b/.exec(s.title)?.[0];
  const web = /^https?:\/\//i.test(s.path);
  return `@misc{${key},\n  title = {{${bibEscape(s.title)}}},\n${year ? `  year = {${year}},\n` : ""}  howpublished = {${web ? `\\url{${s.path}}` : `Local document: ${bibEscape(s.path.replace(/\\/g, "/"))}`}},\n  note = {Indexed by D-ASK}\n}`;
}

/** Keys for a report's sources (D1, D2, …): a library paper's own key when its URL/DOI matches, otherwise one derived from the title. */
export function keysFor(sources: BibSource[], library: Paper[]): Map<string, { key: string; bib: string }> {
  const out = new Map<string, { key: string; bib: string }>();
  const used = new Set<string>();
  for (const s of sources) {
    const paper = library.find((p) => p.url === s.path || (p.doi && s.path.includes(p.doi)));
    let key = paper?.key ?? bibKey([], null, s.title).replace(/^anon/, "src");
    while (used.has(key)) key += "x";
    used.add(key);
    out.set(s.label, { key, bib: paper ? bibtexForPaper({ ...paper, key }) : bibtexForLocal(s, key) });
  }
  return out;
}

/** Markdown report (as written by runResearch) -> a standalone LaTeX article; [Dk] markers -> \cite{key}. */
export function reportToLatex(md: string, keys: Map<string, { key: string }>, title: string): string {
  const cite = (s: string) => latexEscape(s).replace(/\[(D\d+)\]/g, (_m, d: string) => (keys.get(d) ? `\\cite{${keys.get(d)!.key}}` : `[${d}]`));
  const out: string[] = ["\\documentclass[11pt]{article}", "\\usepackage[utf8]{inputenc}", "\\usepackage[T1]{fontenc}", "\\usepackage{hyperref}", "\\usepackage{booktabs}",
    `\\title{${latexEscape(title)}}`, "\\author{Generated by D-ASK from locally indexed sources}", "\\date{\\today}", "\\begin{document}", "\\maketitle", ""];
  let inList = false;
  const closeList = () => { if (inList) { out.push("\\end{itemize}"); inList = false; } };
  for (const raw of md.split("\n")) {
    const line = raw.trimEnd();
    if (/^# /.test(line)) continue;                                   // the title
    if (/^\|/.test(line)) continue;                                    // the evidence table is summarised in the sections
    if (/^## /.test(line)) { closeList(); out.push(`\\section{${latexEscape(line.slice(3))}}`); continue; }
    if (/^\*\*Evidence\*\*$/.test(line)) { closeList(); out.push("\\paragraph{Evidence}"); continue; }
    if (/^(- |\d+\. )/.test(line)) { if (!inList) { out.push("\\begin{itemize}"); inList = true; } out.push(`  \\item ${cite(line.replace(/^(- |\d+\. )/, "").replace(/\*\*/g, "").replace(/`/g, ""))}`); continue; }
    closeList();
    if (!line) { out.push(""); continue; }
    out.push(cite(line.replace(/^> /, "").replace(/\*\*([^*]+)\*\*/g, "$1").replace(/\*([^*]+)\*/g, "$1").replace(/`/g, "")));
  }
  closeList();
  out.push("", "\\bibliographystyle{plain}", "\\bibliography{references}", "\\end{document}", "");
  return out.join("\n");
}

/** A research-proposal skeleton in LaTeX, filled with the report's evidence where it has some; every gap is marked for the author. */
export function proposalLatex(topic: string, question: string, sections: { title: string; synthesis: string | null; extracts: { doc: string; text: string }[] }[], keys: Map<string, { key: string }>): string {
  const cite = (d: string) => (keys.get(d) ? `\\cite{${keys.get(d)!.key}}` : `[${d}]`);
  const evidence = (titles: string[]) => {
    const s = sections.filter((x) => titles.some((t) => x.title.toLowerCase().includes(t)));
    const parts = s.flatMap((x) => [x.synthesis ? latexEscape(x.synthesis).replace(/\[(D\d+)\]/g, (_m, d: string) => cite(d)) : null,
      ...x.extracts.slice(0, 3).map((e) => "``" + latexEscape(e.text) + "'' " + cite(e.doc))]).filter(Boolean);
    return parts.length ? parts.join("\n\n") : "\\textbf{[To be written by the author: the indexed sources contain no evidence for this section.]}";
  };
  return ["\\documentclass[11pt]{article}", "\\usepackage[utf8]{inputenc}", "\\usepackage[T1]{fontenc}", "\\usepackage{hyperref}",
    `\\title{Research proposal: ${latexEscape(topic)}}`, "\\author{[Author]}", "\\date{\\today}", "\\begin{document}", "\\maketitle",
    "\\begin{abstract}", "\\textbf{[To be written by the author.]} This draft was assembled by D-ASK from locally indexed sources; quoted passages are verbatim and cited.", "\\end{abstract}",
    "\\section{Background and motivation}", evidence(["background", "problem", "context", "overview"]),
    "\\section{Research question}", latexEscape(question),
    "\\section{Related work}", evidence(["method", "approach", "findings", "results"]),
    "\\section{Research gaps}", evidence(["limit", "gap", "future"]),
    "\\section{Hypotheses}", "\\textbf{[To be written by the author. D-ASK does not invent hypotheses; base them on the gaps above.]}",
    "\\section{Methodology}", evidence(["data", "method", "evaluation"]),
    "\\section{Experimental design and evaluation}", "\\textbf{[To be written by the author: datasets, baselines, metrics, statistical tests.]}",
    "\\section{Timeline}", "\\textbf{[To be written by the author.]}",
    "\\bibliographystyle{plain}", "\\bibliography{references}", "\\end{document}", ""].join("\n");
}
